CREATE TABLE assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    symbol VARCHAR(32) NOT NULL,
    name VARCHAR(255) NOT NULL,
    asset_type VARCHAR(32) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    created_at TIMESTAMPTZ(6) NOT NULL,
    CONSTRAINT assets_pkey PRIMARY KEY (id),
    CONSTRAINT uk_assets_symbol UNIQUE (symbol)
);

CREATE TABLE transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    asset_id BIGINT NOT NULL,
    type VARCHAR(32) NOT NULL,
    occurred_at DATE NOT NULL,
    quantity NUMERIC(19, 8) NOT NULL,
    unit_price NUMERIC(19, 4) NOT NULL,
    fees NUMERIC(19, 4) NOT NULL,
    notes VARCHAR(500),
    CONSTRAINT transactions_pkey PRIMARY KEY (id),
    CONSTRAINT fk_transactions_asset FOREIGN KEY (asset_id) REFERENCES assets (id)
);

CREATE INDEX idx_transactions_asset_id_occurred_at ON transactions (asset_id, occurred_at DESC);
